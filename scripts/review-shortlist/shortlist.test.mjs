// A fake GitHub holding one pull request.
function github(pr) {
  return async url => {
    const bare = url.replace(/[?&]per_page=100&page=\d+$/, '');
    const first = /[?&]page=1$/.test(url) || !/[?&]page=\d+$/.test(url);
    const list = value => (first ? value : []);
    const base = `/repos/${repository}`;
    if (bare === `${base}/pulls/${pr.number}`) {
      return { number: pr.number, title: pr.title, head: { sha: pr.head }, base: { ref: 'main' }, merged_at: pr.merged_at ?? null,
        merge_commit_sha: pr.merge_commit ?? null, user: pr.user ?? { login: 'dev', type: 'User' }, body: pr.body ?? '' };
    }
    if (bare === `${base}/pulls/${pr.number}/commits`) return list(pr.commits ?? []);
    if (bare === `${base}/pulls/${pr.number}/files`) return list(pr.files.map(([filename, status = 'modified']) => ({ filename, status })));
    if (bare === `${base}/commits/${pr.head}/check-runs?filter=latest`) return { check_runs: list(pr.runs ?? []) };
    if (bare === `${base}/commits/${pr.head}/status`) return { statuses: [] };
    if (bare === `${base}/pulls/${pr.number}/reviews`) return list(pr.reviews ?? []);
    if (bare === `${base}/pulls/${pr.number}/comments`) return list(pr.comments ?? []);
    throw new Error(`unexpected ${url}`);
  };
}

// A fake repository: the tree at the head, and what changed on main since.
function repo({ head, tree, later = {} }) {
  return (command, ...args) => {
    if (command === 'fetch') return '';
    if (command === 'ls-tree') return Object.keys(tree).join('\n');
    if (command === 'show') return tree[args[0].slice(head.length + 1)];
    if (command === 'merge-base') return 'base000\n';
    if (command === 'log') return later[args.at(-1)] ?? '';
    if (command === 'grep') {
      const patterns = [];
      for (let i = 0; args[i] !== head; i++) if (args[i] === '-e') patterns.push(args[++i]);
      const files = args.slice(args.indexOf('--') + 1);
      const lines = files.flatMap(file => patterns.filter(pattern => tree[file].includes(pattern)).map(pattern => `${head}:${file}:${pattern}`));
      if (!lines.length) throw Object.assign(new Error('no match'), { status: 1 });
      return lines.join('\n');
    }
    throw new Error(`unexpected git ${command}`);
  };
}

const agentPull = {
  number: 7, title: 'Add a CSV export', head: 'head123', body: 'Implements spec/caveat-export-0.1.md.',
  commits: [{ commit: { message: 'Add a CSV export\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>' } }],
  files: [['web/export.js'], ['web/export.test.mjs', 'added'], ['web/legacy.js'], ['docs/EXPORT.md'], ['web/old-export.js', 'removed']],
  runs: [{ name: 'test', status: 'completed', conclusion: 'success' }],
};
const tree = {
  'web/export.js': 'export const csv = rows => rows.join("\\n"); // spec/caveat-export-0.1.md',
  'web/export.test.mjs': "import { csv } from './export.js';",
  'web/legacy.js': 'export const legacy = 1;',
  'scripts/test-web.mjs': "import './legacy.js';",
  'docs/EXPORT.md': 'See caveat-export-0.1.md and caveat-other-0.1.md.',
  'spec/caveat-export-0.1.md': '# Export',
  'spec/caveat-other-0.1.md': '# Other',
};

async function shortlist(pr, options = {}) {
  const pull = await gatherPull({ api: github(pr), repository, number: pr.number });
  const facts = buildFacts(pull, gatherLinks({ git: repo({ head: pr.head, tree, later: options.later }), pull }));
  return { pull, facts, ...decide({ kit, template, facts }) };
}
const byFile = rows => Object.fromEntries(rows.map(row => [row.file, row]));

test('test files and the names a test uses for a file', () => {
  for (const name of ['kit/test/docs.test.mjs', 'scripts/test-break.mjs', 'runtime/tests/modules.rs', 'ledger/project.scenarios.json', 'python/tests/test_wheel.py']) assert.ok(isTest(name), name);
  for (const name of ['web/break.js', 'runtime/tests/fixtures/a.json', 'kit/test/fixtures/x/README.md', 'tests/adversarial/README.md', 'docs/TESTING.md']) assert.ok(!isTest(name), name);
  assert.equal(nameOf('web/break-check.js'), 'break-check.js');
  assert.equal(nameOf('runtime/src/mod.rs'), null);
  assert.equal(nameOf('Makefile'), null);
});

test("an agent's pull request lists every file nothing but the agent backs", async () => {
  const { pull, rows, facts } = await shortlist(agentPull);
  assert.equal(pull.agent, true);
  assert.equal(pull.author, 'Claude Code');
  const files = byFile(rows);
  assert.equal(files['web/legacy.js'].listed, false);
  assert.equal(files['web/legacy.js'].why, 'tests from before this pull request name it and pass on its head');
  assert.equal(files['web/export.js'].listed, true);
  assert.equal(files['web/export.js'].why, 'only tests the agent wrote in this pull request back it');
  assert.equal(files['web/export.test.mjs'].why, "it rests on the agent's word only");
  assert.equal(files['web/old-export.js'].why, "it rests on the agent's word only");
  // The description cites the export spec, so export.js rests on it; the doc
  // names another spec in passing, which it does not rest on.
  assert.deepEqual(files['web/export.js'].specs.map(link => link.spec), ['spec/caveat-export-0.1.md']);
  assert.deepEqual(files['docs/EXPORT.md'].specs.map(link => link.spec), ['spec/caveat-export-0.1.md']);
  assert.match(renderProgram(template, facts), /entity f1 kind file at pr;  # web\/export\.js/);
});

test("failed checks take the earlier test's backing away", async () => {
  const { rows } = await shortlist({ ...agentPull, runs: [{ name: 'test', status: 'completed', conclusion: 'failure' }] });
  assert.equal(byFile(rows)['web/legacy.js'].listed, true);
});

test("a person's comment or approval counts; the agent's own comments and stale approvals do not", async () => {
  const person = { login: 'reviewer', type: 'User' };
  const { rows } = await shortlist({ ...agentPull, comments: [
    { user: person, path: 'docs/EXPORT.md', body: 'Reads well.' },
    { user: person, path: 'web/export.js', body: `Fixed the edge case.${FOOTER}` },
  ], reviews: [{ user: person, state: 'APPROVED', commit_id: 'older456', body: '' }] });
  const files = byFile(rows);
  assert.equal(files['docs/EXPORT.md'].listed, false);
  assert.equal(files['docs/EXPORT.md'].why, 'a person reviewed it');
  assert.equal(files['web/export.js'].listed, true);
  const approved = await shortlist({ ...agentPull, reviews: [{ user: person, state: 'APPROVED', commit_id: 'head123', body: 'LGTM' }] });
  assert.ok(approved.rows.every(row => !row.listed));
});

test('a test or spec changed on main since puts back exactly the files that rested on it', async () => {
  const { rows } = await shortlist({ ...agentPull, merged_at: '2026-10-26T00:00:00Z', merge_commit: 'merge789' },
    { later: { 'scripts/test-web.mjs': 'abc1234 Rewrite the web test\n' } });
  const files = byFile(rows);
  assert.equal(files['web/legacy.js'].listed, true);
  assert.equal(files['web/legacy.js'].why, 'check it again: a test or spec it rested on has changed since');
  assert.deepEqual(files['web/legacy.js'].changed, [{ name: 'scripts/test-web.mjs', kind: 'test', commit: 'abc1234 Rewrite the web test' }]);
  assert.equal(files['docs/EXPORT.md'].why, "it rests on the agent's word only");
});

test("a person's pull request lists nothing", async () => {
  const { pull, rows } = await shortlist({ ...agentPull, commits: [{ commit: { message: 'Add a CSV export' } }] });
  assert.equal(pull.agent, false);
  assert.ok(rows.every(row => !row.listed && row.why === 'written by a person'));
});

test('the command prints the list and the reasons', async () => {
  const out = [];
  await main(['7'], { api: github(agentPull), git: repo({ head: agentPull.head, tree }), kit, log: line => out.push(line) });
  const text = out.join('\n');
  assert.match(text, /^#7 Add a CSV export\n  written by Claude Code \(an agent\); all 1 check results passed on head123; no approval from a person at its head/);
  assert.match(text, /Check these 4 of 5 files:/);
  assert.match(text, /  web\/export\.js\n      only tests the agent wrote in this pull request back it\n      tests it wrote: web\/export\.test\.mjs/);
  assert.match(text, /Off the list:\n  web\/legacy\.js: tests from before this pull request name it and pass on its head \(scripts\/test-web\.mjs\)/);
});

