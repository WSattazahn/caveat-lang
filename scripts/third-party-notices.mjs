// Writes THIRD_PARTY_NOTICES.md: the license notices of the Rust crates that
// are compiled into the Caveat WebAssembly runtime. Build-time crates (proc
// macros and their dependencies) are not in the binary and are not listed.
//
//   node scripts/third-party-notices.mjs           write the file
//   node scripts/third-party-notices.mjs --check   fail if it is out of date
//
// Needs cargo and the locked crates in the local registry (cargo fetch).
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = path.join(root, 'runtime', 'Cargo.toml');
const output = path.join(root, 'THIRD_PARTY_NOTICES.md');
const cargo = args => execFileSync('cargo', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

// Both published builds: full (default features) and reactive-only.
const linked = new Map();
for (const features of [[], ['--no-default-features']]) {
  const tree = cargo(['tree', '--manifest-path', manifest, '--locked', '--target', 'wasm32-unknown-unknown', ...features,
    '-e', 'normal,no-proc-macro', '--prefix', 'none', '--format', '{p}|{l}']);
  for (const line of tree.split(/\r?\n/)) {
    const match = /^(\S+) v(\S+)[^|]*\|(.*)$/.exec(line.trim());
    if (!match || match[1] === 'caveat-runtime') continue;
    linked.set(`${match[1]} ${match[2]}`, { name: match[1], version: match[2], license: match[3].trim() });
  }
}

const metadata = JSON.parse(cargo(['metadata', '--manifest-path', manifest, '--locked', '--format-version', '1']));
const directories = new Map(metadata.packages.map(item => [`${item.name} ${item.version}`, path.dirname(item.manifest_path)]));

const sections = [];
for (const crate of [...linked.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  if (!/\bMIT\b/.test(crate.license)) throw new Error(`${crate.name} ${crate.version} is not available under MIT: ${crate.license}`);
  const directory = directories.get(`${crate.name} ${crate.version}`);
  const mit = path.join(directory, 'LICENSE-MIT');
  if (!existsSync(mit)) throw new Error(`${crate.name} ${crate.version} has no LICENSE-MIT in ${directory}`);
  const texts = [['MIT', await readFile(mit, 'utf8')]];
  if (/Unicode/.test(crate.license)) texts.push(['Unicode-3.0', await readFile(path.join(directory, 'LICENSE-UNICODE'), 'utf8')]);
  sections.push([
    `## ${crate.name} ${crate.version}`,
    '',
    `Declared license: \`${crate.license}\`. Used under ${texts.map(([name]) => name).join(' and ')}.`,
    '',
    ...texts.flatMap(([name, text]) => [`${name}:`, '', '```text', text.replace(/\r\n/g, '\n').trimEnd(), '```', '']),
  ].join('\n'));
}

const document = `${[
  '# Third-party notices',
  '',
  'Caveat\'s own code and documentation are under the MIT License in [LICENSE](LICENSE).',
  'The Caveat WebAssembly runtime (`caveat_runtime_bg.wasm` and its generated',
  '`caveat_runtime.js`) also contains the Rust crates below, compiled in. Each is',
  'used under the MIT License, chosen where a crate offers a choice; `unicode-ident`',
  'also carries the Unicode License. Their notices follow unchanged.',
  '',
  'The browser site additionally ships three.js, whose license is copied beside it',
  'as `vendor/THREE-LICENSE.txt`.',
  '',
  'Generated by `scripts/third-party-notices.mjs` from `runtime/Cargo.lock`.',
  '',
].join('\n')}\n${sections.join('\n')}`;

if (process.argv.includes('--check')) {
  const existing = existsSync(output) ? await readFile(output, 'utf8') : '';
  if (existing !== document) {
    console.error('THIRD_PARTY_NOTICES.md is out of date; run node scripts/third-party-notices.mjs');
    process.exitCode = 1;
  } else {
    console.log(`THIRD_PARTY_NOTICES.md is current: ${linked.size} crates.`);
  }
} else {
  await writeFile(output, document);
  console.log(`Wrote THIRD_PARTY_NOTICES.md: ${linked.size} crates.`);
}
