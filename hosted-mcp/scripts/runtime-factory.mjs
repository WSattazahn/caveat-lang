// Writes src/generated/runtime-factory.mjs from the pinned package's
// wasm-bindgen glue (runtime/caveat_runtime.js). The glue keeps its instance
// in module state and initializes once, so a bundle that imports it can never
// replace an instance that trapped. The generated module wraps the same text
// in a function: each call returns new bindings with their own state, which
// the Worker instantiates from the module compiled at upload.
// wrangler.toml runs this before every build; npm test runs it first too.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const glueUrl = new URL('../node_modules/caveat-lang/runtime/caveat_runtime.js', import.meta.url);
const outUrl = new URL('../src/generated/runtime-factory.mjs', import.meta.url);

export function factorySource(glue) {
  const names = [];
  const body = glue.split('\n').map(line => {
    if (/^import\b/.test(line)) throw new Error(`the runtime glue imports a module: ${line}`);
    let match = /^export (class|function|const|let) ([A-Za-z_$][\w$]*)/.exec(line);
    if (match) { names.push([match[2], match[2]]); return line.slice('export '.length); }
    match = /^export \{ ([^}]*) \};$/.exec(line);
    if (match) {
      for (const item of match[1].split(',').map(text => text.trim()).filter(Boolean)) {
        const [local, exported = local] = item.split(/\s+as\s+/);
        names.push([exported, local]);
      }
      return '';
    }
    match = /^export default ([A-Za-z_$][\w$]*);$/.exec(line);
    if (match) { names.push(['default', match[1]]); return ''; }
    if (/^export\b/.test(line)) throw new Error(`unexpected export form in the runtime glue: ${line}`);
    return line;
  });
  const exported = names.map(([name]) => name);
  for (const required of ['default', 'initSync', 'WebReactiveSession']) {
    if (!exported.includes(required)) throw new Error(`the runtime glue does not export ${required}`);
  }
  const fields = names.map(([name, local]) => name === local ? `    ${name},` : `    ${JSON.stringify(name)}: ${local},`);
  return `// Generated by scripts/runtime-factory.mjs from caveat-lang's runtime glue; do not edit.
export function createBindings() {
${body.join('\n')}
  return {
${fields.join('\n')}
  };
}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const glue = await readFile(glueUrl, 'utf8');
  await mkdir(new URL('.', outUrl), { recursive: true });
  await writeFile(outUrl, factorySource(glue));
}
