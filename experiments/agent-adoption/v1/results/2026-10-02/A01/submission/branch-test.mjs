import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {loadRuntimeFromDirectory} from 'caveat-lang/node';
const source=readFileSync('node_modules/caveat-lang/examples/agent-evidence/assessment.cav','utf8');
const liveRuntime=await loadRuntimeFromDirectory();
const live=liveRuntime.open(source);
assert.equal(live.dispatch('observe',{confidence:85}).outcome,'accepted');
assert.equal(live.dispatch('assess').outcome,'accepted');
const saved=live.save(),snapshot=live.snapshot();
const branchRuntime=await loadRuntimeFromDirectory();
assert.notEqual(branchRuntime,liveRuntime);
assert.deepEqual(branchRuntime.identity,liveRuntime.identity);
const branch=branchRuntime.restore(source,saved);
assert.deepEqual(branch.snapshot(),snapshot);
assert.equal(branch.dispatch('observe',{confidence:40}).outcome,'accepted');
const refusal=branch.dispatch('assess');
assert.equal(refusal.outcome,'rejected');
assert.equal(refusal.code,'reject');
assert.equal(branch.snapshot().bindings.assessment.verdict,'reopened');
assert.equal(live.save(),saved);
assert.deepEqual(live.snapshot(),snapshot);
writeFileSync('branch-results.json',JSON.stringify({sameRuntimeIdentity:true,branchOutcome:refusal,branchSnapshot:branch.snapshot(),liveUnchanged:true,liveSnapshot:snapshot},null,2));
branch.close();live.close();
console.log('Separate-loader save/restore alternative passed; hypothetical observe 40 + assess refused, live save and snapshot unchanged. No trap or process isolation tested.');
